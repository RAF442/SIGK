"""Training, validation, checkpointing and reproducibility of both loss variants."""
from __future__ import annotations

from importlib.metadata import version as package_version
import math
import os
import random
import time

from data import ROOT, Patches, digest, load_json, require_prepared, save_json, sha256

import numpy as np
import torch
from torch.utils.data import DataLoader
from tqdm import tqdm
from pytorch_msssim import ssim

from model import UNet

VARIANTS = ("l1", "l1_ssim")


def seed_all(seed):
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    if torch.cuda.is_available():
        torch.cuda.manual_seed_all(seed)


def device_for(args):
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu") if args.device == "auto" else torch.device(args.device)
    if device.type == "cuda" and not torch.cuda.is_available():
        raise RuntimeError("CUDA niedostepna. Uruchom start.ps1 check lub wybierz --device cpu.")
    torch.set_num_threads(min(8, os.cpu_count() or 1))
    # Same software/hardware and seeds are repeatable; other CUDA versions may differ.
    torch.backends.cudnn.benchmark = False
    torch.backends.cudnn.deterministic = True
    return device


def train_config(args, meta):
    sources = ("main.py", "data.py", "train.py", "evaluate.py")
    return {"protocol": meta["signature"], "seed": args.seed, "width": args.width,
            "ev": args.ev, "gamma": args.gamma, "epochs": args.epochs, "steps": args.steps,
            "batch": args.batch, "patch": args.patch, "lr": args.lr, "ssim_weight": args.ssim_weight,
            "patience": args.patience, "amp": not args.no_amp, "torch": str(torch.__version__),
            "model_sha256": sha256(ROOT / "model.py"),
            "pipeline_sha256": digest({name: sha256(ROOT / name) for name in sources})}


def save_checkpoint(path, value):
    temp = path.with_suffix(".pt.tmp")
    torch.save(value, temp)
    temp.replace(path)


def load_checkpoint(path, device="cpu"):
    # Checkpoints are generated by this program in the local results directory.
    return torch.load(path, map_location=device, weights_only=False)


@torch.inference_mode()
def validate(model, loader, device):
    model.eval()
    psnrs, ssims = [], []
    for x, y in loader:
        x, y = x.to(device), y.to(device)
        pred = model(x)
        mse = (pred - y).square().mean(dim=(1, 2, 3)).clamp_min(1e-12)
        psnrs.extend((-10 * mse.log10()).cpu().tolist())
        ssims.extend(ssim(pred, y, data_range=1.0, size_average=False).cpu().tolist())
    return float(np.mean(psnrs)), float(np.mean(ssims))


def train(args):
    meta = require_prepared(args)
    device = device_for(args)
    config = train_config(args, meta)
    signature = digest(config)
    args.results.mkdir(parents=True, exist_ok=True)
    config_path = args.results / "config.json"
    if config_path.exists() and load_json(config_path)["signature"] != signature:
        raise RuntimeError("Istniejace wyniki maja inna konfiguracje. Uzyj nowego --results, aby ich nie nadpisac.")
    if not config_path.exists():
        save_json(config_path, {"signature": signature, "config": config, "protocol": meta,
                               "device": str(device), "gpu": torch.cuda.get_device_name(device) if device.type == "cuda" else "CPU",
                               "packages": {name: package_version(name) for name in
                                            ("torch", "torchvision", "rawpy", "numpy", "scikit-image", "lpips", "pytorch-msssim")}})
    datasets = None
    for variant in VARIANTS:
        folder = args.results / variant
        folder.mkdir(exist_ok=True)
        last_path, best_path = folder / "last.pt", folder / "best.pt"
        last = load_checkpoint(last_path) if last_path.exists() else None
        if last and last["signature"] != signature:
            raise RuntimeError("Checkpoint pochodzi z innej konfiguracji.")
        if last and last.get("complete"):
            if not best_path.exists():
                raise RuntimeError(f"Brak {best_path}. Przywroc wagi najlepszego modelu.")
            save_json(folder / "history.json", last["history"])
            print(f"{variant}: trening juz zakonczony; pomijam.")
            continue
        if datasets is None:
            datasets = (Patches(args, [r for r in meta["items"] if r["split"] == "train"]),
                        Patches(args, [r for r in meta["items"] if r["split"] == "val"], training=False))
        train_data, val_data = datasets
        train_loader = DataLoader(train_data, batch_size=args.batch, num_workers=0, pin_memory=device.type == "cuda")
        val_loader = DataLoader(val_data, batch_size=args.batch, num_workers=0)
        seed_all(args.seed)  # Identical initialization and crops for both loss variants.
        model = UNet(args.width, args.ev, args.gamma).to(device)
        optimizer = torch.optim.Adam(model.parameters(), lr=args.lr)
        scheduler = torch.optim.lr_scheduler.CosineAnnealingLR(optimizer, T_max=args.epochs, eta_min=args.lr * 0.05)
        amp = device.type == "cuda" and not args.no_amp
        scaler = torch.amp.GradScaler("cuda", enabled=amp)
        history, best, stale, first_epoch = [], -math.inf, 0, 1
        if last:
            model.load_state_dict(last["model"])
            optimizer.load_state_dict(last["optimizer"])
            scheduler.load_state_dict(last["scheduler"])
            scaler.load_state_dict(last["scaler"])
            history, best, stale, first_epoch = last["history"], last["best"], last["stale"], last["epoch"] + 1
        print(f"\n{variant}: {sum(p.numel() for p in model.parameters()):,} parametrow, {device}, start od epoki {first_epoch}")
        for epoch in range(first_epoch, args.epochs + 1):
            start = time.perf_counter()
            train_data.epoch = epoch
            seed_all(args.seed + epoch)
            model.train()
            total = 0.0
            bar = tqdm(train_loader, desc=f"{variant} {epoch}/{args.epochs}", leave=False)
            for x, y in bar:
                x, y = x.to(device, non_blocking=True), y.to(device, non_blocking=True)
                optimizer.zero_grad(set_to_none=True)
                with torch.autocast(device_type=device.type, enabled=amp):
                    pred = model(x)
                    loss = torch.nn.functional.l1_loss(pred, y)
                if variant == "l1_ssim":
                    # SSIM statistics are evaluated in float32, outside autocast.
                    loss = loss.float() + args.ssim_weight * (1.0 - ssim(pred.float(), y.float(), data_range=1.0))
                if not torch.isfinite(loss):
                    raise RuntimeError("Nieskonczona strata; sprawdz dane lub uruchom z --no-amp.")
                scaler.scale(loss).backward()
                scaler.unscale_(optimizer)
                torch.nn.utils.clip_grad_norm_(model.parameters(), 1.0)
                scaler.step(optimizer)
                scaler.update()
                total += loss.item()
                bar.set_postfix(loss=f"{loss.item():.4f}")
            val_psnr, val_ssim = validate(model, val_loader, device)
            scheduler.step()
            elapsed = time.perf_counter() - start
            row = {"epoch": epoch, "loss": total / len(train_loader), "val_psnr": val_psnr,
                   "val_ssim": val_ssim, "seconds": elapsed, "lr": optimizer.param_groups[0]["lr"]}
            history.append(row)
            improved = val_psnr > best
            best, stale = (val_psnr, 0) if improved else (best, stale + 1)
            state = {"signature": signature, "config": config, "variant": variant, "epoch": epoch,
                     "model": model.state_dict(), "optimizer": optimizer.state_dict(),
                     "scheduler": scheduler.state_dict(), "scaler": scaler.state_dict(),
                     "history": history, "best": best, "stale": stale,
                     "complete": epoch == args.epochs or stale >= args.patience}
            if improved:
                save_checkpoint(best_path, {k: state[k] for k in ("signature", "config", "variant", "epoch", "model", "best")})
            save_checkpoint(last_path, state)
            save_json(folder / "history.json", history)
            remaining = (args.epochs - epoch) * np.mean([r["seconds"] for r in history[-5:]]) / 60
            print(f"{variant} epoka {epoch}: loss={row['loss']:.4f}, val PSNR={val_psnr:.2f}, SSIM={val_ssim:.4f}, {elapsed:.1f}s; do limitu ~{remaining:.0f} min")
            if state["complete"]:
                if stale >= args.patience:
                    print(f"Wczesne zatrzymanie: {args.patience} epok bez poprawy PSNR walidacji.")
                break
        del model, optimizer, scheduler, scaler
        if device.type == "cuda":
            torch.cuda.empty_cache()

